    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            if (!txtCodigo.isEditable()) {
                throw new IllegalArgumentException("Hay una cita seleccionada. Use Actualizar para modificarla o Nuevo para crear otra.");
            }
            Mascota m = mascotaElegida();
            String estado = (String) cbEstado.getSelectedItem();
 
            Cita c = new Cita(txtCodigo.getText(), txtFecha.getText(),
                    txtHora.getText(), txtMotivo.getText(), estado, m);
            GestorVeterinaria.listaCitas.add(c);
            listarCitas();
            mensaje("Cita registrada correctamente.");
            nuevo();
        } catch (IllegalArgumentException | VeterinariaExcepcion ex) {
            error(ex.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

