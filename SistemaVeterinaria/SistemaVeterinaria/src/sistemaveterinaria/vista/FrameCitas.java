    private javax.swing.table.DefaultTableModel modeloTabla;
    private void configurarTabla() {
        // Tabla de solo lectura: las ediciones se hacen en el formulario
        modeloTabla = new javax.swing.table.DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int col) { return false; }
        };
        modeloTabla.addColumn("Código");
        modeloTabla.addColumn("Fecha");
        modeloTabla.addColumn("Hora");
        modeloTabla.addColumn("Mascota");
        modeloTabla.addColumn("Propietario");
        modeloTabla.addColumn("Motivo");
        modeloTabla.addColumn("Estado");
        
        tblCitas.setModel(modeloTabla);
    }
    private void cargarCombos() {
        // Estado
        cbEstado.removeAllItems();
        cbEstado.addItem("Pendiente");
        cbEstado.addItem("Atendida");
        cbEstado.addItem("Cancelada");
        
        // Mascota (Cargando desde el Gestor). Posición en el combo = índice en la lista + 1
        cbMascota.removeAllItems();
        cbMascota.addItem("Seleccione la Mascota");
        for (Mascota m : GestorVeterinaria.listaMascotas) {
            cbMascota.addItem(m.getNombre() + " (" + m.getPropietario().getNombre() + ")");
        }
    }
    private void listarCitas() {
        modeloTabla.setRowCount(0);
        for (Cita c : GestorVeterinaria.listaCitas) {
            Object[] fila = {
                c.getCodigo(),
                c.getFecha(),
                c.getHora(),
                c.getMascota().getNombre(),
                c.getMascota().getPropietario().getNombre(),
                c.getMotivo(),
                c.getEstado()
            };
            modeloTabla.addRow(fila);
        }
    }
    private void nuevo() {
        txtCodigo.setEditable(true);   // Modo nueva cita
        txtCodigo.setText("");
        txtFecha.setText("");
        txtHora.setText("");
        txtMotivo.setText("");
        cbEstado.setSelectedIndex(0);
        cbMascota.setSelectedIndex(0);
        tblCitas.clearSelection();
        txtCodigo.requestFocus();
    }
    private void cargarFilaEnCampos() {
        int f = tblCitas.getSelectedRow();
        if (f < 0) return;
        Cita c = GestorVeterinaria.listaCitas.get(f);
        txtCodigo.setText(c.getCodigo());
        txtCodigo.setEditable(false);   // Modo edición: el código es la "llave", no se cambia
        txtFecha.setText(c.getFecha());
        txtHora.setText(c.getHora());
        txtMotivo.setText(c.getMotivo());
        cbEstado.setSelectedItem(c.getEstado());
        cbMascota.setSelectedIndex(GestorVeterinaria.listaMascotas.indexOf(c.getMascota()) + 1);
    }
    private Mascota mascotaElegida() {
        int i = cbMascota.getSelectedIndex();
        if (i <= 0) throw new IllegalArgumentException("Debe seleccionar una mascota.");
        return GestorVeterinaria.listaMascotas.get(i - 1);
    }
