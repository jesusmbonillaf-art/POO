    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int filaSeleccionada = tblCitas.getSelectedRow();
    
        if (filaSeleccionada < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una cita de la tabla para eliminar.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        Cita c = GestorVeterinaria.listaCitas.get(filaSeleccionada);
    
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar la cita " + c.getCodigo() + "?", "Confirmar eliminación", javax.swing.JOptionPane.YES_NO_OPTION);
    
        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            GestorVeterinaria.listaCitas.remove(c); // Elimina el objeto Cita directamente
            listarCitas();
            nuevo();
            txtCodigo.setEditable(true); // En tu método nuevo() usas setEditable, mejor mantener consistencia
            javax.swing.JOptionPane.showMessageDialog(this, "Cita eliminada.", "Información", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

